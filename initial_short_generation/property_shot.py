"""# 12. Add a dark cinematic gradient

##### This helps white text remain readable over property photos.
"""

def add_gradient(frame):

    h, w = frame.shape[:2]

    gradient = np.zeros(
        (h, w, 3),
        dtype=np.float32
    )

    # Bottom gradient
    for y in range(h):

        strength = max(
            0,
            (y / h - 0.55) / 0.45
        )

        gradient[y, :, :] = (
            strength * 80
        )

    result = (
        frame.astype(np.float32)
        - gradient
    )

    return np.clip(
        result,
        0,
        255
    ).astype(np.uint8)

"""# 13. Animated text opacity"""

def fade_opacity(
    progress,
    fade_in=0.12,
    fade_out=0.85
):

    if progress < fade_in:

        return int(
            255 *
            progress /
            fade_in
        )

    if progress > fade_out:

        return int(
            255 *
            (1 - progress) /
            (1 - fade_out)
        )

    return 255

