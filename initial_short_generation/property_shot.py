def get_font(size, bold=False):

    path = (
        FONT_BOLD_PATH
        if bold
        else FONT_PATH
    )

    return ImageFont.truetype(
        path,
        size
    )


def add_text(
    frame,
    text,
    xy,
    size=50,
    bold=False,
    opacity=255,
    color=(255, 255, 255)
):

    pil = PILImage.fromarray(frame)

    overlay = PILImage.new(
        "RGBA",
        pil.size,
        (0, 0, 0, 0)
    )

    draw = ImageDraw.Draw(
        overlay
    )

    font = get_font(
        size,
        bold
    )

    x, y = xy

    # Shadow
    draw.text(
        (x + 3, y + 3),
        text,
        font=font,
        fill=(0, 0, 0, int(opacity * 0.7))
    )

    # Main text
    draw.text(
        (x, y),
        text,
        font=font,
        fill=(color[0],
              color[1],
              color[2],
              opacity)
    )

    result = PILImage.alpha_composite(
        pil.convert("RGBA"),
        overlay
    )

    return np.array(
        result.convert("RGB")
    )

def add_logo(frame, logo_path, x=55, y=70, width=220):

    if not logo_path or not os.path.exists(logo_path):
        return frame

    base = PILImage.fromarray(frame).convert("RGBA")

    logo = PILImage.open(logo_path).convert("RGBA")

    # Resize while keeping aspect ratio
    ratio = width / logo.width
    height = int(logo.height * ratio)

    logo = logo.resize(
        (width, height),
        PILImage.Resampling.LANCZOS
    )

    base.alpha_composite(
        logo,
        (x, y)
    )

    return np.array(
        base.convert("RGB")
    )

