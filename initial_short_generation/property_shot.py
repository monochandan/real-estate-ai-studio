"""#9. Improved parallax engine

#### This is function, but modified for the vertical video and with different movement styles.
"""

def smoothstep(x):
    return x * x * (3 - 2 * x)


def create_parallax_frame(
    image,
    depth,
    progress,
    move_x=0.04,
    move_y=0.015,
    zoom_start=1.0,
    zoom_end=1.08,
    direction=1
):

    image = np.asarray(
        image,
        dtype=np.uint8
    )

    depth = np.asarray(
        depth,
        dtype=np.float32
    )

    h, w = image.shape[:2]

    if depth.shape[:2] != (h, w):

        depth = cv2.resize(
            depth,
            (w, h),
            interpolation=cv2.INTER_LINEAR
        )

    # Normalize depth
    d_min = depth.min()
    d_max = depth.max()

    if d_max > d_min:

        d = (
            depth - d_min
        ) / (
            d_max - d_min
        )

    else:

        d = np.zeros_like(depth)

    # Center depth
    d = d - 0.5

    # Smooth
    d = cv2.GaussianBlur(
        d,
        (0, 0),
        4
    )

    # Smooth cinematic motion
    p = smoothstep(progress)

    # Horizontal camera movement
    x_shift = (
        np.sin(p * np.pi)
        * move_x
        * direction
    )

    # Vertical movement
    y_shift = (
        np.sin(p * np.pi)
        * move_y
    )

    # Zoom
    zoom = (
        zoom_start
        + (zoom_end - zoom_start) * p
    )

    # Coordinates
    xx, yy = np.meshgrid(
        np.arange(w, dtype=np.float32),
        np.arange(h, dtype=np.float32)
    )

    # Depth parallax
    map_x = xx + (
        x_shift * d * w
    )

    map_y = yy + (
        y_shift * d * h
    )

    # Zoom around center
    cx = w / 2
    cy = h / 2

    map_x = (
        cx
        + (map_x - cx) / zoom
    )

    map_y = (
        cy
        + (map_y - cy) / zoom
    )

    map_x = np.asarray(
        map_x,
        dtype=np.float32
    )

    map_y = np.asarray(
        map_y,
        dtype=np.float32
    )

    frame = cv2.remap(
        image,
        map_x,
        map_y,
        interpolation=cv2.INTER_LINEAR,
        borderMode=cv2.BORDER_REFLECT101
    )

    return frame

