"""#8. Vertical image preparation

##### This is important.

##### A normal property photo might be:

##### 1920 × 1080

##### while Reels need:

##### 1080 × 1920

##### Rather than simply stretching the photo, we'll scale it to cover the vertical frame.
"""

def prepare_vertical(image, depth):

    target_ratio = WIDTH / HEIGHT

    h, w = image.shape[:2]

    current_ratio = w / h

    if current_ratio > target_ratio:

        # Image is too wide
        new_h = HEIGHT
        new_w = int(w * HEIGHT / h)

    else:

        # Image is too tall
        new_w = WIDTH
        new_h = int(h * WIDTH / w)

    image_resized = cv2.resize(
        image,
        (new_w, new_h),
        interpolation=cv2.INTER_LANCZOS4
    )

    depth_resized = cv2.resize(
        depth,
        (new_w, new_h),
        interpolation=cv2.INTER_LINEAR
    )

    x = (new_w - WIDTH) // 2
    y = (new_h - HEIGHT) // 2

    image_crop = image_resized[
        y:y+HEIGHT,
        x:x+WIDTH
    ]

    depth_crop = depth_resized[
        y:y+HEIGHT,
        x:x+WIDTH
    ]

    return image_crop, depth_crop


